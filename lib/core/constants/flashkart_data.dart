/// Ders bazında flash kartları
Map<String, List<FlashKart>> get dersBazindaFlashKartlar {
  final map = <String, List<FlashKart>>{};
  for (final kart in flashKartlar) {
    map.putIfAbsent(kart.ders, () => []).add(kart);
  }
  return map;
}

/// ID ile flash kart bulma
FlashKart? flashKartBul(String id) {
  try {
    return flashKartlar.firstWhere((k) => k.id == id);
  } catch (_) {
    return null;
  }
}